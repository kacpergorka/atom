# Standardowe biblioteki
from typing import TypedDict

class Zastępstwo(TypedDict):
    zidentyfikowane: bool
    dzien: str | None
    grupa: str | None
    nauczyciel: str
    lekcja: int | None
    opis: str | None
    zastepca: str | None
    uwagi: str | None


class Zastępstwa(TypedDict):
    identyfikator: str | None
    dni: list[str]
    informacje: str
    skrocone: bool | None
    zastepstwa: list[Zastępstwo] | None
