# Zewnętrzne biblioteki
from pydantic import BaseModel

class AtomowyElementListy(BaseModel):
    """
    Model elementu listy zwracanego przez API aplikacji Atom.
    """

    identyfikator: str
    nazwa: str


class AtomoweListy(BaseModel):
    """
    Model list oddziałów i nauczycieli zwracanych przez API aplikacji Atom.
    """

    oddzialy: list[AtomowyElementListy]
    nauczyciele: list[AtomowyElementListy]
