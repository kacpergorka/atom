# Zewnętrzne biblioteki
from pydantic import BaseModel

class AtomoweZastepstwo(BaseModel):
    nauczyciel: str
    lekcja: int | None
    opis: str | None
    zastepca: str | None
    uwagi: str | None


class AtomoweZastepstwa(BaseModel):
    dzien: str | None
    informacje: list[str]
    zastepstwa: list[AtomoweZastepstwo] | None
